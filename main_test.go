const cloudsSample = `# generated by kolla
clouds:
  kolla-admin:
    auth:
      auth_url: http://192.168.19.63:5000  # keystone
      username: admin
      password: "p#ss:word"
      project_name: admin
      domain_name: default
      user_domain_name: Default
    region_name: RegionOne
    interface: internal
    verify: false
  other:
    auth:
      auth_url: http://x:5000
`

func TestLoadCloud(t *testing.T) {
	f := filepath.Join(t.TempDir(), "clouds.yaml")
	os.WriteFile(f, []byte(cloudsSample), 0o600)
	c, err := loadCloud(f, "kolla-admin")
	if err != nil {
		t.Fatal(err)
	}
	if c.AuthURL != "http://192.168.19.63:5000" || c.Password != "p#ss:word" || c.Username != "admin" ||
		c.ProjectName != "admin" || c.ProjectDomainName != "default" || c.UserDomainName != "Default" ||
		c.Region != "RegionOne" || c.Interface != "internal" || !c.Insecure {
		t.Fatalf("unexpected cfg: %+v", c)
	}
	if _, err := loadCloud(f, "nope"); err == nil || !strings.Contains(err.Error(), "available: kolla-admin, other") {
		t.Fatalf("want not-found error, got %v", err)
	}
}

type fakeCloud struct {
	mu        sync.Mutex
	srv       *httptest.Server
	migs      []map[string]any
	processed int64
	auths     int
	reject    bool
}

func newFakeCloud(t *testing.T) *fakeCloud {
	fc := &fakeCloud{}
	mux := http.NewServeMux()
	mux.HandleFunc("/v3/auth/tokens", func(w http.ResponseWriter, r *http.Request) {
		fc.mu.Lock()
		fc.auths++
		fc.mu.Unlock()
		var body map[string]any
		json.NewDecoder(r.Body).Decode(&body)
		w.Header().Set("X-Subject-Token", "tok")
		w.WriteHeader(201)
		json.NewEncoder(w).Encode(map[string]any{"token": map[string]any{
			"expires_at": time.Now().Add(time.Hour).UTC().Format(time.RFC3339),
			"catalog": []any{map[string]any{"type": "compute", "endpoints": []any{
				map[string]any{"interface": "internal", "region": "RegionOne", "url": fc.srv.URL + "/v2.1"},
				map[string]any{"interface": "public", "region": "RegionOne", "url": "http://wrong:1/v2.1"},
			}}},
		}})
	})
	mux.HandleFunc("/v2.1/os-migrations", func(w http.ResponseWriter, r *http.Request) {
		if r.Header.Get("X-Auth-Token") != "tok" || r.Header.Get("X-OpenStack-Nova-API-Version") == "" {
			w.WriteHeader(401)
			return
		}
		fc.mu.Lock()
		defer fc.mu.Unlock()
		q := r.URL.Query()
		var out []map[string]any
		for _, m := range fc.migs {
			if s := q.Get("status"); s != "" && m["status"] != s {
				continue
			}
			if i := q.Get("instance_uuid"); i != "" && m["instance_uuid"] != i {
				continue
			}
			out = append(out, m)
		}
		json.NewEncoder(w).Encode(map[string]any{"migrations": out})
	})
	mux.HandleFunc("/v2.1/servers/", func(w http.ResponseWriter, r *http.Request) {
		fc.mu.Lock()
		defer fc.mu.Unlock()
		fc.processed += 100 << 20
		json.NewEncoder(w).Encode(map[string]any{"migration": map[string]any{
			"memory_total_bytes": int64(1 << 30), "memory_processed_bytes": fc.processed,
			"memory_remaining_bytes": int64(1<<30) - fc.processed,
			"disk_total_bytes":       nil, "disk_processed_bytes": nil, "disk_remaining_bytes": nil,
		}})
	})
	fc.srv = httptest.NewServer(mux)
	t.Cleanup(fc.srv.Close)
	return fc
}

func (fc *fakeCloud) poller(t *testing.T) *Poller {
	cfg := CloudConfig{AuthURL: fc.srv.URL, Username: "admin", Password: "x", ProjectName: "admin", Interface: "internal", Region: "RegionOne"}
	hc, _ := newHTTPClient(cfg, false)
	n := &novaClient{ks: &keystone{cfg: cfg, hc: hc}, hc: hc, microversion: "2.80"}
	return newPoller(n, 5*time.Second, 24*time.Hour, slog.New(slog.NewTextHandler(os.Stderr, nil)))
}

func metricsText(p *Poller) string {
	var sb strings.Builder
	p.writeMetrics(&sb)
	return sb.String()
}

func mustContain(t *testing.T, text string, subs ...string) {
	t.Helper()
	for _, s := range subs {
		if !strings.Contains(text, s) {
			t.Errorf("metrics missing %q\n--- got ---\n%s", s, text)
		}
	}
}

func ts(d time.Duration) string {
	return time.Now().UTC().Add(d).Format("2006-01-02T15:04:05.000000")
}

func TestPollLifecycle(t *testing.T) {
	fc := newFakeCloud(t)
	fc.migs = []map[string]any{
		{"id": 1, "uuid": "u-done", "instance_uuid": "i1", "source_compute": "c1", "dest_compute": "c2", "status": "completed", "migration_type": "live-migration", "created_at": ts(-10 * time.Minute), "updated_at": ts(-10*time.Minute + 42*time.Second)},
		{"id": 2, "uuid": "u-fail", "instance_uuid": "i2", "source_compute": "c2", "dest_compute": "c3", "status": "error", "migration_type": "live-migration", "created_at": ts(-5 * time.Minute), "updated_at": ts(-5*time.Minute + 8*time.Second)},
		{"id": 3, "uuid": "u-run", "instance_uuid": "i3", "source_compute": "c1", "dest_compute": "c3", "status": "running", "migration_type": "live-migration", "created_at": ts(-20 * time.Second), "updated_at": ts(-time.Second)},
	}
	p := fc.poller(t)
	ctx := context.Background()

	if err := p.poll(ctx); err != nil {
		t.Fatal(err)
	}
	time.Sleep(120 * time.Millisecond)
	if err := p.poll(ctx); err != nil {
		t.Fatal(err)
	}
	out := metricsText(p)
	mustContain(t, out,
		`nova_live_migration_in_progress 1`,
		`nova_live_migrations_total{source="c1",dest="c2",status="completed"} 1`,
		`nova_live_migrations_total{source="c2",dest="c3",status="error"} 1`,
		`nova_live_migration_duration_seconds_bucket{source="c1",dest="c2",status="completed",le="45"} 1`,
		`nova_live_migration_duration_seconds_bucket{source="c1",dest="c2",status="completed",le="30"} 0`,
		`nova_live_migration_duration_seconds_count{source="c1",dest="c2",status="completed"} 1`,
		`nova_live_migration_last_duration_seconds{source="c1",dest="c2",status="completed"} 42`,
		`nova_live_migration_memory_total_bytes{migration="u-run",instance="i3",source="c1",dest="c3"} 1.073741824e+09`,
		`nova_live_migration_memory_speed_bytes_per_second{migration="u-run"`,
		`nova_live_migration_memory_progress_ratio{migration="u-run"`,
		`nova_migrate_exporter_up 0`, // up is set by run(), not poll()
	)
	if strings.Contains(out, "disk_total_bytes{") {
		t.Errorf("null disk fields must not be exported:\n%s", out)
	}

	// polling again must not double count finished migrations
	p.poll(ctx)
	if !strings.Contains(metricsText(p), `status="completed"} 1`) {
		t.Errorf("finished migration double counted")
	}

	// running migration completes
	fc.mu.Lock()
	fc.migs[2]["status"] = "completed"
	fc.migs[2]["updated_at"] = ts(0)
	fc.mu.Unlock()
	p.poll(ctx)
	out = metricsText(p)
	mustContain(t, out,
		`nova_live_migration_in_progress 0`,
		`nova_live_migrations_total{source="c1",dest="c3",status="completed"} 1`,
		`nova_live_migration_last_avg_speed_bytes_per_second{source="c1",dest="c3",status="completed"}`,
		`nova_live_migration_last_memory_processed_bytes{source="c1",dest="c3",status="completed"}`,
	)
	if strings.Contains(out, `migration="u-run"`) {
		t.Errorf("finished migration still exported as in-flight")
	}
}

func TestReauthOn401(t *testing.T) {
	fc := newFakeCloud(t)
	p := fc.poller(t)
	if err := p.poll(context.Background()); err != nil {
		t.Fatal(err)
	}
	p.nova.ks.mu.Lock()
	p.nova.ks.token = "stale"
	p.nova.ks.mu.Unlock()
	if err := p.poll(context.Background()); err != nil {
		t.Fatalf("expected transparent re-auth, got %v", err)
	}
	if fc.auths < 2 {
		t.Fatalf("expected re-authentication, auths=%d", fc.auths)
	}
}

